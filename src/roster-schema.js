// The squad_patch input, defined once: the JSON Schema OpenCode advertises to
// the model, the runtime validation the tool handler runs (Code Mode can call
// a tool without the advertised schema being enforced), and the input type
// all come from these Zod schemas. Installed-model variant checks and the
// deletion guard stay at the application boundary (src/squad-tools.js,
// src/squad-apply.js): they need the host and the disk.

import { z } from "zod";

import { ARG_DESCRIPTIONS } from "./squad-tools.js";

const MODEL_ID_RE = /^[^/#]+\/[^#]+$/;

/** @param {string} field */
const nonBlank = (field) => {
  const message = `${field} must be a non-empty string when present`;
  return z.string({ error: message }).refine((s) => s.trim() !== "", { message });
};

const STEPS_MESSAGE = "steps must be a positive integer when present";

const agentEntry = z.strictObject(
  {
    variant: nonBlank("variant").describe(ARG_DESCRIPTIONS["agent.variant"]).optional(),
    notes: nonBlank("notes").describe(ARG_DESCRIPTIONS["agent.notes"]).optional(),
    steps: z
      .number({ error: STEPS_MESSAGE })
      .int({ error: STEPS_MESSAGE })
      .positive({ error: STEPS_MESSAGE })
      .describe(ARG_DESCRIPTIONS["agent.steps"])
      .optional(),
    disable: z
      .boolean({ error: "disable must be a boolean when present" })
      .describe(ARG_DESCRIPTIONS["agent.disable"])
      .optional(),
  },
  {
    error: (iss) =>
      iss.code === "invalid_type" ? "must be an object (use {} for no overrides)" : undefined,
  },
);

/** @param {string} key  roster key, for the message */
const agentMap = (key) =>
  z.record(z.string().regex(MODEL_ID_RE), agentEntry, {
    error: (iss) =>
      iss.code === "invalid_type" ? `${key} must be an object keyed by model id` : undefined,
  });

/** The roster document squad_dump prints and squad_patch takes back. */
const RosterSchema = z.strictObject({
  grunts: agentMap("grunts").describe(ARG_DESCRIPTIONS["patch.grunts"]).optional(),
  drills: agentMap("drills").describe(ARG_DESCRIPTIONS["patch.drills"]).optional(),
});

/** squad_patch's whole input: the roster plus the call's own switches. */
const SquadPatchInputSchema = RosterSchema.extend({
  allow_remove: z.boolean().describe(ARG_DESCRIPTIONS["patch.allow_remove"]).optional(),
  directory: z.string().describe(ARG_DESCRIPTIONS["patch.directory"]).optional(),
});

/** @typedef {z.input<typeof SquadPatchInputSchema>} SquadPatchInput */

/**
 * The JSON Schema advertised for squad_patch. Zod adds a `$schema` URI, a
 * `propertyNames` for record keys and the safe-integer `maximum` of an int;
 * none of them is needed by a model and some providers reject unfamiliar
 * keywords, so they are dropped and the advertised shape stays the plain
 * subset the tool always sent. The model-id and non-blank rules are enforced
 * at runtime by the same schema.
 */
const { $schema: _dialect, ...patchJsonSchema } = z.toJSONSchema(SquadPatchInputSchema, {
  io: "input",
  override: ({ jsonSchema }) => {
    delete jsonSchema.propertyNames;
    if (jsonSchema.maximum === Number.MAX_SAFE_INTEGER) delete jsonSchema.maximum;
    // A string's own non-blank / id pattern is runtime-only (see above).
    delete jsonSchema.pattern;
  },
});
export const SQUAD_PATCH_INPUT = patchJsonSchema;

/** `grunts["a/b"].variant` for a Zod issue path. */
function where(path) {
  let out = "";
  for (const [i, seg] of path.entries()) {
    if (i === 0) out = String(seg);
    else if (i === 1) out += `["${String(seg)}"]`;
    else out += `.${String(seg)}`;
  }
  return out;
}

/**
 * Validate an edited roster and return every problem at once — someone fixing
 * an edited document should not discover the mistakes one run at a time.
 *
 * `description` is refused with a pointer to where it belongs: the plugin
 * builds it from model_data.json (describeAgent in workers.js), so a
 * hand-written one would be overwritten at the next start anyway.
 *
 * @param {unknown} doc
 * @returns {string[]}  empty when valid
 */
export function validateRoster(doc) {
  if (typeof doc !== "object" || doc === null || Array.isArray(doc)) {
    return ["roster must be a JSON object"];
  }
  const result = RosterSchema.safeParse(doc);
  if (result.success) return [];
  const errors = [];
  for (const issue of result.error.issues) {
    const at = where(issue.path);
    if (issue.code === "unrecognized_keys" && issue.path.length === 0) {
      for (const key of issue.keys) {
        errors.push(
          `unknown top-level key "${key}" (expected ${Object.keys(RosterSchema.shape).join(", ")})`,
        );
      }
    } else if (issue.code === "unrecognized_keys") {
      for (const key of issue.keys) {
        errors.push(
          key === "description"
            ? `${at}.description: descriptions are generated by the plugin from ` +
                `model_data.json — put a routing rule in its models["${String(issue.path[1])}"].info ` +
                "instead, and leave description out."
            : `${at} has unknown key "${key}"`,
        );
      }
    } else if (issue.path.length <= 1) {
      errors.push(issue.message);
    } else if (issue.code === "invalid_key") {
      errors.push(`${at}: "${String(issue.path.at(-1))}" is not a provider/model id`);
    } else if (issue.path.length === 2) {
      errors.push(`${at} ${issue.message}`);
    } else {
      errors.push(`${where(issue.path.slice(0, 2))}.${issue.message}`);
    }
  }
  return errors;
}
